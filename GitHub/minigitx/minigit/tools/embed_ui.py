#!/usr/bin/env python3
"""Regenerates src/UiPage.cpp from the files in ui/.
Only needed if you want your edited page built INTO minigit.exe. While you are
just editing, minigit.exe already loads the files from the ui/ folder next to it."""
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
def read(name):
    with open(os.path.join(root, "ui", name), encoding="utf-8") as f:
        return f.read()
parts = [("UI_HTML", "MGHTML", "index.html"), ("UI_CSS", "MGCSS", "style.css"), ("UI_JS", "MGJS", "app.js"),
         ("UI_EDITOR_HTML", "MGEHTML", "editor.html"), ("UI_EDITOR_JS", "MGEJS", "editor.js")]
out = '#include "UiPage.h"\n\n// Generated by tools/embed_ui.py from the files in ui/. Do not edit by hand.\n'
for var, delim, name in parts:
    text = read(name)
    assert ")" + delim + '"' not in text
    out += "const char* const %s = R\"%s(%s)%s\";\n\n" % (var, delim, text, delim)
with open(os.path.join(root, "src", "UiPage.cpp"), "w", encoding="utf-8") as f:
    f.write(out)
print("wrote src/UiPage.cpp")
